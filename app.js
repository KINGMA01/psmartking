function formatCanadianAddress(hit) {
  const a = hit.address || {};
  const number = a.house_number || "";
  const street = a.road || a.pedestrian || a.residential || a.neighbourhood || "";
  const borough = a.suburb || a.city_district || "";
  const city = a.city || a.town || a.village || a.municipality || "";
  const postcodeRaw = String(a.postcode || "").toUpperCase().replace(/\s+/g, "");
  const postcode = /^[A-Z]\d[A-Z]\d[A-Z]\d$/.test(postcodeRaw)
    ? postcodeRaw.slice(0, 3) + " " + postcodeRaw.slice(3)
    : String(a.postcode || "").toUpperCase().replace(/\s+/g, " ").trim();
  const line1 = [number, street].filter(Boolean).join(" ").replace(/\s+/g, " ").trim();
  const locality = borough && tokenizePlace(borough) !== tokenizePlace(city) ? borough : city;
  const parts = [];
  if (line1) parts.push(line1);
  if (locality) parts.push(locality);
  let cityLine = parts.join(", ");
  if (cityLine) cityLine += " QC";
  else cityLine = "QC";
  if (postcode) cityLine += " " + postcode;
  return cityLine;
}

function hitLocalities(hit) {
  const a = hit.address || {};
  return [a.suburb, a.city_district, a.neighbourhood, a.city, a.town, a.village, a.municipality, a.county]
    .filter(Boolean);
}

function ringContains(ring, lat, lng) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const xi = ring[i][0];
    const yi = ring[i][1];
    const xj = ring[j][0];
    const yj = ring[j][1];
    const hit = yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / ((yj - yi) || 1e-12) + xi;
    if (hit) inside = !inside;
  }
  return inside;
}

function pointInPolygonCoords(coords, lat, lng) {
  if (!coords || !coords.length) return false;
  if (!ringContains(coords[0], lat, lng)) return false;
  for (let i = 1; i < coords.length; i += 1) {
    if (ringContains(coords[i], lat, lng)) return false;
  }
  return true;
}

function pointInCoverageGeo(lat, lng) {
  if (!coverageGeojson) return null;
  const feats = coverageGeojson.features || [];
  for (const feat of feats) {
    const geom = feat.geometry;
    if (!geom) continue;
    if (geom.type === "Polygon" && pointInPolygonCoords(geom.coordinates, lat, lng)) return true;
    if (geom.type === "MultiPolygon") {
      if (geom.coordinates.some((poly) => pointInPolygonCoords(poly, lat, lng))) return true;
    }
  }
  return false;
}

function coverageStatusFor(query) {
  const q = foldText(query);
  if (!q) return "empty";
  const compact = q.replace(/\s+/g, "");
  if (/^[a-z]\d[a-z]\d[a-z]\d$/i.test(compact) || /^[a-z]\d[a-z]$/i.test(compact)) {
    if (/^h7/i.test(compact)) return "outside";
    if (/^h[0-9]/i.test(compact)) return "covered";
  }
  if (placeMatchesCovered(q)) return "covered";
  if (cityIsOutside(q)) return "outside";
  if (/\d/.test(q) && /rue|avenue|av\.|boul|boulevard|chemin|ch\.|place|cres|crescent|street|road|drive/i.test(q)) {
    return "search";
  }
  return "empty";
}

