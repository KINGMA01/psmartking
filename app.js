function tokenizePlace(value) {
  return foldText(value).replace(/[^a-z0-9]+/g, " ").trim();
}

function placeMatchesCovered(value) {
  const t = tokenizePlace(value);
  if (!t) return false;
  if (t === "montreal" || /(^| )montreal( |$)/.test(t) || t.includes("agglomeration de montreal")) return true;
  return COVERED_LOCALITIES.some((place) => {
    const p = tokenizePlace(place);
    return t === p || t.startsWith(p + " ") || t.endsWith(" " + p) || t.includes(" " + p + " ");
  });
}

function cityIsOutside(value) {
  const t = tokenizePlace(value);
  if (!t) return false;
  if (t === "quebec" || t === "ville de quebec" || t === "quebec city") return true;
  return OUTSIDE_CITIES.some((place) => t === tokenizePlace(place));
}

