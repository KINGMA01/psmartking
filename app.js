async function pickCoverageSuggest(index) {
  const item = coverageSuggestItems[index];
  const input = document.getElementById("coverage-q");
  if (!item || !input) return;
  hideCoverageSuggest();
  if (item.hit) {
    coveragePickedHit = item.hit;
    input.value = displayAddress(item.hit) || item.label;
    await runCoverageSearch(input.value, item.hit);
    return;
  }
  if (!item.prediction) return;
  try {
    const hit = await placePredictionToHit(item.prediction);
    coveragePickedHit = hit;
    input.value = displayAddress(hit) || item.label;
    await runCoverageSearch(input.value, hit);
  } catch {
    paintCoverageResult("notfound");
  }
}

async function fetchAddressSuggestions(query) {
  const trimmed = String(query || "").trim();
  if (trimmed.length < 3) {
    hideCoverageSuggest();
    return;
  }
  try {
    const rows = await googleSuggestAddresses(trimmed);
    const seen = new Set();
    const items = [];
    rows.forEach((row) => {
      const prediction = row.placePrediction;
      const label = predictionLabel(prediction);
      const key = foldText(label);
      if (!label || seen.has(key)) return;
      seen.add(key);
      items.push({
        label,
        borough: "",
        prediction,
      });
    });
    if (document.getElementById("coverage-q")?.value.trim() !== trimmed) return;
    renderCoverageSuggest(items);
  } catch {
    hideCoverageSuggest();
  }
}

async function runCoverageSearch(query, presetHit) {
  const trimmed = String(query || "").trim();
  if (!trimmed) {
    paintCoverageResult("empty");
    return;
  }
  paintCoverageResult("searching");
  let hit = presetHit || null;
  if (!hit && coveragePickedHit && foldText(displayAddress(coveragePickedHit)) === foldText(trimmed)) {
    hit = coveragePickedHit;
  }
  if (!hit) {
    try {
      hit = await googleGeocodeAddress(trimmed);
    } catch {
      hit = null;
    }
  }
  coveragePickedHit = hit;
  const found = statusFromHit(hit, trimmed);
  if (found.status === "empty") {
    paintCoverageResult("empty");
    return;
  }
  if (found.lat != null && !Number.isNaN(found.lat) && found.lng != null && !Number.isNaN(found.lng)) {
    placeCoverageMarker(found.lat, found.lng, found.status);
  }
  paintCoverageResult(found.status);
}

