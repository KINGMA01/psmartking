async function coverageStatusAt(lat, lng) {
  const inside = pointInCoverageGeo(lat, lng);
  if (inside !== null) return inside;
  const hit = await reverseGeocodePoint(lat, lng).catch(() => null);
  return hit ? hitIsCovered(hit, lat, lng) : null;
}

