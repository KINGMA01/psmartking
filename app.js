function hitIsCovered(hit, lat, lng) {
  const pip = lat != null && lng != null ? pointInCoverageGeo(lat, lng) : null;
  if (pip === true) return true;
  if (pip === false) return false;
  const places = hitLocalities(hit);
  if (places.some((place) => cityIsOutside(place) && !placeMatchesCovered(place))) return false;
  return places.some((place) => placeMatchesCovered(place));
}

function statusFromHit(hit, query) {
  if (hit) {
    const lat = parseFloat(hit.lat);
    const lng = parseFloat(hit.lon);
    const covered = hitIsCovered(hit, lat, lng);
    return { status: covered ? "covered" : "outside", lat, lng, label: displayAddress(hit) };
  }
  const status = coverageStatusFor(query);
  if (status === "search") return { status: "notfound", lat: null, lng: null };
  if (status === "covered") return { status, lat: 45.52, lng: -73.65 };
  return { status, lat: null, lng: null };
}

