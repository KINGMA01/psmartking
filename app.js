const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
const WAITLIST_KEY = "psmartking-waitlist";
const LANG_KEY = "psmartking-lang";

function lookup(lang, key) {
  return key.split(".").reduce((acc, part) => (acc ? acc[part] : undefined), COPY[lang]);
}

function setLanguage(lang) {
  const next = COPY[lang] ? lang : "fr";
  document.documentElement.lang = next === "fr" ? "fr" : "en";
  localStorage.setItem(LANG_KEY, next);

  const page = document.documentElement.dataset.page || "home";
  const meta = (COPY[next].pages && COPY[next].pages[page]) || COPY[next].meta;
  document.title = meta.title;
  const desc = document.querySelector('meta[name="description"]');
  const ogTitle = document.querySelector('meta[property="og:title"]');
  const ogDesc = document.querySelector('meta[property="og:description"]');
  const ogLocale = document.querySelector('meta[property="og:locale"]');
  const twTitle = document.querySelector('meta[name="twitter:title"]');
  const twDesc = document.querySelector('meta[name="twitter:description"]');
  if (desc) desc.setAttribute("content", meta.description);
  if (ogTitle) ogTitle.setAttribute("content", meta.title);
  if (ogDesc) ogDesc.setAttribute("content", meta.description);
  if (ogLocale) ogLocale.setAttribute("content", next === "fr" ? "fr_CA" : "en_CA");
  if (twTitle) twTitle.setAttribute("content", meta.title);
  if (twDesc) twDesc.setAttribute("content", meta.description);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = lookup(next, el.dataset.i18n);
    if (typeof value === "string") el.textContent = value;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const value = lookup(next, el.dataset.i18nPlaceholder);
    if (typeof value === "string") el.setAttribute("placeholder", value);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const value = lookup(next, el.dataset.i18nAria);
    if (typeof value === "string") el.setAttribute("aria-label", value);
  });

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const active = btn.dataset.lang === next;
    btn.classList.toggle("is-active", active);
    btn.setAttribute("aria-pressed", String(active));
  });
  refreshCoverageLang();
}

function closeMobileNav() {
  const header = document.querySelector(".site-header");
  const panel = document.getElementById("nav-mobile");
  const toggle = document.querySelector(".nav-toggle");
  header.classList.remove("is-open");
  panel.hidden = true;
  toggle.setAttribute("aria-expanded", "false");
}

function initHeaderScroll() {
  const header = document.querySelector(".site-header");
  if (!header) return;
  const band = document.querySelector(".hero, .page-hero, .cta-band");
  const update = () => {
    if (!band) {
      header.classList.add("is-solid");
      return;
    }
    const passed = band.getBoundingClientRect().bottom <= header.getBoundingClientRect().bottom;
    header.classList.toggle("is-solid", passed);
  };
  update();
  window.addEventListener("scroll", update, { passive: true });
  window.addEventListener("resize", update);
}

function initNav() {
  const header = document.querySelector(".site-header");
  const panel = document.getElementById("nav-mobile");
  const toggle = document.querySelector(".nav-toggle");

  toggle.addEventListener("click", () => {
    const open = header.classList.toggle("is-open");
    panel.hidden = !open;
    toggle.setAttribute("aria-expanded", String(open));
  });

  panel.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", closeMobileNav);
  });
}

function markWaitlistDone() {
  document.querySelectorAll("[data-waitlist]").forEach((form) => {
    form.classList.add("is-done");
    const success = form.nextElementSibling;
    if (success && success.classList.contains("form-success")) {
      success.hidden = false;
    }
  });
}

function initWaitlist() {
  if (localStorage.getItem(WAITLIST_KEY) === "1") {
    markWaitlistDone();
  }

  document.querySelectorAll("[data-waitlist]").forEach((form) => {
    form.addEventListener("submit", (event) => {
      event.preventDefault();
      const input = form.querySelector('input[type="email"]');
      const valid = EMAIL_RE.test((input.value || "").trim());
      form.classList.toggle("form-error", !valid);
      input.setAttribute("aria-invalid", String(!valid));
      if (!valid) {
        input.focus();
        return;
      }
      localStorage.setItem(WAITLIST_KEY, "1");
      markWaitlistDone();
    });
  });
}

