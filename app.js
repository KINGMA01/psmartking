function initCoverage() {
  const form = document.querySelector("[data-coverage]");
  const holder = document.getElementById("coverage-map");
  const input = form ? form.querySelector("input") : null;
  const list = document.getElementById("coverage-suggest");

  if (holder) {
    ensureGoogleMapsReady()
      .then(() => setupGoogleCoverageMap(holder))
      .catch(() => showCoverageMapFallback(holder));
  }

  if (!form || !input) return;

  form.addEventListener("submit", (event) => {
    event.preventDefault();
    hideCoverageSuggest();
    const query = (input.value || "").trim();
    runCoverageSearch(query);
    if (!query) input.focus();
  });

  input.addEventListener("input", () => {
    coveragePickedHit = null;
    const query = input.value.trim();
    window.clearTimeout(coverageSuggestTimer);
    if (query.length < 3) {
      hideCoverageSuggest();
      return;
    }
    coverageSuggestTimer = window.setTimeout(() => fetchAddressSuggestions(query), 380);
  });

  input.addEventListener("keydown", (event) => {
    if (list && !list.hidden && coverageSuggestItems.length) {
      if (event.key === "ArrowDown") {
        event.preventDefault();
        setActiveSuggest(coverageActiveIndex + 1);
      } else if (event.key === "ArrowUp") {
        event.preventDefault();
        setActiveSuggest(coverageActiveIndex - 1);
      } else if (event.key === "Enter" && coverageActiveIndex >= 0) {
        event.preventDefault();
        pickCoverageSuggest(coverageActiveIndex);
      } else if (event.key === "Escape") {
        hideCoverageSuggest();
      }
    }
  });

  list?.addEventListener("mousedown", (event) => {
    const btn = event.target.closest("[data-suggest-index]");
    if (!btn) return;
    event.preventDefault();
    pickCoverageSuggest(Number(btn.getAttribute("data-suggest-index")));
  });

  document.addEventListener("click", (event) => {
    if (!form.contains(event.target)) hideCoverageSuggest();
  });
}

