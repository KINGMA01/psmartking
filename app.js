function addressComponentValue(components, type, short) {
  const list = Array.isArray(components) ? components : [];
  const found = list.find((item) => (item.types || []).includes(type));
  if (!found) return "";
  if (short) return found.shortText || found.short_name || "";
  return found.longText || found.long_name || "";
}

function placeToHit(place) {
  if (!place) return null;
  const { lat, lng } = latLngOf(place.location);
  const comps = place.addressComponents || place.address_components || [];
  return {
    lat,
    lon: lng,
    formatted: String(place.formattedAddress || place.formatted_address || "").replace(/, Canada$/i, "").trim(),
    address: {
      house_number: addressComponentValue(comps, "street_number"),
      road: addressComponentValue(comps, "route"),
      suburb:
        addressComponentValue(comps, "sublocality_level_1") ||
        addressComponentValue(comps, "sublocality") ||
        addressComponentValue(comps, "neighborhood"),
      city:
        addressComponentValue(comps, "locality") ||
        addressComponentValue(comps, "administrative_area_level_3"),
      postcode: addressComponentValue(comps, "postal_code"),
    },
  };
}

